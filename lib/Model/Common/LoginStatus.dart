  ///
  /// 연결이 안 되거나, 응답이 늦거나, 서버가 5xx 를 주거나, 응답을 읽지 못한
  /// 경우다. 토큰은 지우지 않는다. 잠깐 끊긴 것일 수 있어서 다시 시도하면
